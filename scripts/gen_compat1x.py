"""Generate src/generated/compat1x.c: the data of the `alteruphono-1` projection.

It carries, from alteruphono 1.x, only what is not a feature table:
- the label vocabulary and its categories (`features/ipa.py` FEATURE_CATEGORIES
  and the tone values), which fix the names and the replacement rule of
  feature modifiers;
- the sound-class pack (`resources/classes.tsv`, FEATURES column only);
- the grapheme universe (`resources/sounds.tsv`, GRAPHEME column only, in file
  order), which 1.x uses as its lookup keys and to render feature sets back
  to graphemes (first match wins).

Feature values come from merkmal at run time, never from these files.

Run from the repository root:  python scripts/gen_compat1x.py
"""

from __future__ import annotations

import csv
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from alteruphono.features.ipa import FEATURE_ALIASES, FEATURE_CATEGORIES, _TONE_VALUES  # noqa: E402

OUT = ROOT / "src" / "generated" / "compat1x.c"
DROPPED_CLASSES = {"XXX"}  # 1.x's "development" entry


def c_string(s: str) -> str:
    out = []
    for b in s.encode("utf-8"):
        if 0x20 <= b < 0x7F and b not in (0x22, 0x5C, 0x3F):
            out.append(chr(b))
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def main() -> None:
    with (ROOT / "resources" / "sounds.tsv").open(encoding="utf-8") as f:
        graphemes = [row["GRAPHEME"] for row in csv.DictReader(f, delimiter="\t")]
    with (ROOT / "resources" / "classes.tsv").open(encoding="utf-8") as f:
        classes = [
            (row["SOUND_CLASS"], row["FEATURES"])
            for row in csv.DictReader(f, delimiter="\t")
            if row["SOUND_CLASS"] not in DROPPED_CLASSES and row["FEATURES"]
        ]
    vocab = list(FEATURE_CATEGORIES.items()) + [(t, None) for t in sorted(_TONE_VALUES)]

    digest = hashlib.sha256()
    for g in graphemes:
        digest.update(g.encode("utf-8") + b"\n")

    lines = [
        "/* Generated by scripts/gen_compat1x.py; do not edit. */",
        "",
        '#include "compat1x.h"',
        "",
        "const ap1_label ap1_vocabulary[] = {",
    ]
    lines += [f"    {{{c_string(n)}, {c_string(c) if c else 'NULL'}}}," for n, c in vocab]
    lines += ["};", f"const size_t ap1_vocabulary_count = {len(vocab)};", ""]
    lines += ["const ap1_alias ap1_aliases[] = {"]
    lines += [f"    {{{c_string(a)}, {c_string(b)}}}," for a, b in FEATURE_ALIASES.items()]
    lines += ["};", f"const size_t ap1_alias_count = {len(FEATURE_ALIASES)};", ""]
    lines += ["const ap1_class ap1_classes[] = {"]
    lines += [f"    {{{c_string(n)}, {c_string(f)}}}," for n, f in classes]
    lines += ["};", f"const size_t ap1_class_count = {len(classes)};", ""]
    lines += ["const char *const ap1_universe[] = {"]
    lines += [f"    {c_string(g)}," for g in graphemes]
    lines += ["};", f"const size_t ap1_universe_count = {len(graphemes)};"]
    lines += [f'const char ap1_universe_sha256[] = "{digest.hexdigest()}";', ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}: {len(vocab)} labels, {len(classes)} classes, {len(graphemes)} graphemes")


if __name__ == "__main__":
    main()
